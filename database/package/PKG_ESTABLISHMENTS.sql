create or replace PACKAGE PKG_ESTABLISHMENTS AS

    PROCEDURE ADD_ESTABLISHMENT
    (
        P_ESTABLISHMENT_NUMBER  IN ESTABLISHMENTS.ESTABLISHMENT_NUMBER%TYPE,
        P_COMPANY_NAME          IN ESTABLISHMENTS.COMPANY_NAME%TYPE,
        P_INSURANCE_OFFICE_CODE IN ESTABLISHMENTS.INSURANCE_OFFICE_CODE%TYPE,
        P_ID                    OUT ESTABLISHMENTS.ID%TYPE
    );

    PROCEDURE UPDATE_ESTABLISHMENT
    (
        P_ID                    IN ESTABLISHMENTS.ID%TYPE,
        P_ESTABLISHMENT_NUMBER  IN ESTABLISHMENTS.ESTABLISHMENT_NUMBER%TYPE,
        P_COMPANY_NAME          IN ESTABLISHMENTS.COMPANY_NAME%TYPE,
        P_INSURANCE_OFFICE_CODE IN ESTABLISHMENTS.INSURANCE_OFFICE_CODE%TYPE
    );

    PROCEDURE DELETE_ESTABLISHMENT
    (
        P_ID IN ESTABLISHMENTS.ID%TYPE
    );

    PROCEDURE GET_ESTABLISHMENT
    (
        P_ID     IN ESTABLISHMENTS.ID%TYPE,
        P_RESULT OUT SYS_REFCURSOR
    );

    PROCEDURE GET_ESTABLISHMENTS
    (
        P_RESULT OUT SYS_REFCURSOR
    );

END PKG_ESTABLISHMENTS;
